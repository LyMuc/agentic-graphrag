def handle_tool_calls(tools: dict[str, any], llm_tool_calls: list[dict[str, any]], updated_question):
    output = []
    called_tools = set()
    if llm_tool_calls:
        print('llm_tool_calls:', llm_tool_calls)
        for tool_call in llm_tool_calls:
            tool_name = tool_call['name']

            # 🚨 skip nếu tool đã gọi rồi
            if tool_name in called_tools:
                continue

            called_tools.add(tool_name)

            function_to_call = tools[tool_call['name']]["function"]
            # 🚨 Override args từ updater
            function_args = {
                "query": updated_question
            } if updated_question else tool_call.get("args", {})
            res = function_to_call(**function_args)
            output.append(res)
    return output

def tool_choice(messages, temperature=0, tools=[], config={}, model=None):
    llm = ChatGroq(api_key=GROQ_API_KEY, model="openai/gpt-oss-120b", temperature=0, max_tokens=2048)
    # Ràng buộc tools vào mô hình Groq
    llm_with_tools = llm.bind_tools(tools)
    return llm_with_tools.invoke(messages).tool_calls

def route_question(question: str, tools: dict[str, any], answers: list[dict[str, str]]):
    llm_tool_calls = tool_choice(
        [
            {
                "role": "system",
                "content": tool_picker_prompt,
            },
            *answers,
            {
                "role": "user",
                "content": f"Câu hỏi của người dùng cần tìm công cụ để giải quyết: '{question}'",
            },
        ],
        tools=[tool["description"] for tool in tools.values()],
    )
    return handle_tool_calls(tools, llm_tool_calls, question)

